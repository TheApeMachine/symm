import { createStore } from "@tanstack/store";

/*
LineageReport mirrors tools/metriclineage's JSON output (report/producerOut/
consumerOut/summaryOut in tools/metriclineage/main.go) exactly. It is a
static, generated artifact — not a live wire frame — regenerated by
`go run ./tools/metriclineage . frontend/public/metric-lineage.json`
(wired into `make run` so it's always current for a live session). Both
components/lineage (the standalone audit page) and components/influence (the
live regression field, annotated with lineage status) read the same fetch and
the same in-memory store so there is exactly one notion of "referenced" across
the app, not two independently-fetched copies that could drift.
*/
export type ConsumerRef = {
	kind: "bound" | "catalog" | "kernel" | "generic";
	consumer: string;
	package: string;
	file: string;
	line: number;
};

export type ProducerRow = {
	id: string;
	source: string;
	metric: string;
	side?: string;
	package: string;
	file: string;
	line: number;
	unit?: string;
	consumers: ConsumerRef[];
	dead: boolean;
	kernelOnly: boolean;
};

export type ConsumerRow = {
	consumer: string;
	kind: "bound" | "catalog" | "kernel" | "generic";
	package: string;
	file: string;
	line: number;
	targets: string[];
};

export type LineageReport = {
	producers: ProducerRow[];
	consumers: ConsumerRow[];
	unresolved: Array<{ package: string; file: string; line: number; reason: string }>;
	summary: {
		totalProducers: number;
		deadProducers: number;
		referencedProducers: number;
		kernelOnlyProducers: number;
		boundConsumerEdges: number;
		catalogConsumerEdges: number;
		kernelConsumerEdges: number;
		genericConsumerEdges: number;
		unresolved: number;
	};
};

export type LineageState = {
	report: LineageReport | null;
	error: string | null;
	byKey: Map<string, ProducerRow>;
};

/*
lineageKey is the join key between a live graph node's (source, metric) pair
— the metric segment recovered from a relation.Coordinate.ID() string, e.g.
"BTC/USD/depthflow/book_imbalance//dimensionless/instantaneous/epoch=1" — and
a ProducerRow's own (source, metric). Side is deliberately excluded: the live
graph's node id embeds a side segment already folded into the id string in a
position this store's caller resolves separately, and the lineage report's
"metric:side" producers are pre-split into metric/side fields, so callers
that don't track side pass "" and still match every side-less metric.
*/
export const lineageKey = (source: string, metric: string): string => `${source}/${metric}`;

const lineageStore = createStore<LineageState>({
	report: null,
	error: null,
	byKey: new Map(),
});

let loadStarted = false;

/*
ensureLineageLoaded fetches the static report at most once per page session
regardless of how many components call it — the report never changes without
a full page reload (it's a build artifact, not a live stream), so repeated
fetches would be pure waste.
*/
export const ensureLineageLoaded = (): void => {
	if (loadStarted) return;
	loadStarted = true;

	fetch("/metric-lineage.json")
		.then((response) => {
			if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
			return response.json() as Promise<LineageReport>;
		})
		.then((report) => {
			const byKey = new Map<string, ProducerRow>();
			for (const row of report.producers) {
				byKey.set(lineageKey(row.source, row.metric), row);
			}
			lineageStore.setState(() => ({ report, error: null, byKey }));
		})
		.catch((err) => {
			lineageStore.setState((state) => ({ ...state, error: String(err) }));
		});
};

export const readLineage = (): LineageState => lineageStore.state;

export const subscribeLineage = (listener: () => void): (() => void) => {
	const subscription = lineageStore.subscribe(listener);
	return () => subscription.unsubscribe();
};

export type LineageStatus = "unreferenced" | "referenced" | "kernelOnly";

export const LINEAGE_STATUS_COLOR: Record<LineageStatus, string> = {
	unreferenced: "var(--down, #e5484d)",
	referenced: "var(--f4, #7c7c85)",
	kernelOnly: "var(--warn, #f5a524)",
};

/*
lineageStatusOf maps a row to its honest status. A "bound" or "catalog"
reference is a DECLARED INPUT — a component names the metric as something it
wants to read — not proof that a named semantic calculation performs a role on
the value. The report therefore renders such rows "referenced" (neutral), never
"used" (which would imply a value was actually consumed by a computation). Only
a metric with no bound/catalog reference at all is "unreferenced"; a metric
whose only lead is a bulk kernel subscription is "kernelOnly".
*/
export const lineageStatusOf = (row: ProducerRow | undefined): LineageStatus | null => {
	if (!row) return null;
	return row.dead ? (row.kernelOnly ? "kernelOnly" : "unreferenced") : "referenced";
};
