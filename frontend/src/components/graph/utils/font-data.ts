/**
 * Get character metrics from char code
 */
export function getCharMetrics(charCode: number): CharMetrics {
	// Handle some special Unicode characters that map to ASCII
	if (charCode === 8216 || charCode === 8217) charCode = 39; // Smart quotes -> '
	if (charCode === 8212) charCode = 45; // Em dash -> -

	const data = fontData[String(charCode)];

	if (!data) {
		return {
			x: 0,
			y: 0,
			width: 0,
			height: 0,
			xoffset: 0,
			yoffset: 0,
			advance: 80.5,
		};
	}

	return {
		x: data[0],
		y: data[1],
		width: data[2],
		height: data[3],
		xoffset: data[4],
		yoffset: data[5],
		advance: data[6],
	};
}

/**
 * Get texture coordinates for a character
 * Returns [left, top, width, height, xoffset, yoffset] normalized to 0-1
 */
export function getTextCoordinates(letter: string): number[] {
	const charCode = letter.charCodeAt(0);
	const metrics = getCharMetrics(charCode);

	return [
		metrics.x / ATLAS_SIZE, // left
		metrics.y / ATLAS_SIZE, // top
		metrics.width / ATLAS_SIZE, // width
		metrics.height / ATLAS_SIZE, // height
		metrics.xoffset / ATLAS_SIZE, // xoffset
		metrics.yoffset / ATLAS_SIZE, // yoffset
	];
}
