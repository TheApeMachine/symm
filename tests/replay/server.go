package replay

import (
	"context"
	"encoding/json"
	"errors"
	"net"
	"net/http"
	"net/http/httptest"
	"strings"
	"sync"
	"time"

	"github.com/gorilla/websocket"
	"github.com/theapemachine/errnie"
	"github.com/theapemachine/symm/hindsight"
)

// Server replaces the remote websocket peer with recorded bytes. It does not
// implement prices, fills, signals, learning, or manufacture protocol responses.
type Server struct {
	server      *httptest.Server
	ctx         context.Context
	mutex       sync.Mutex
	peers       []*peer
	changed     chan struct{}
	endpoints   map[string]string
	Frames      uint64
	Derived     uint64
	First, Last time.Time
	Started     time.Time
	MaxLateness time.Duration
	Source      hindsight.RunID
}

type peer struct {
	connection *websocket.Conn
	endpoint   string
	channels   map[string]map[string]bool
}

func NewServer(ctx context.Context, endpoints map[string]string) *Server {
	server := &Server{ctx: ctx, changed: make(chan struct{}), endpoints: endpoints}
	server.server = httptest.NewServer(http.HandlerFunc(server.accept))
	return server
}

func (server *Server) URL(role string) string {
	return "ws" + strings.TrimPrefix(server.server.URL, "http") + "/" + role
}

func (server *Server) accept(writer http.ResponseWriter, request *http.Request) {
	upgrader := websocket.Upgrader{}
	connection, err := upgrader.Upgrade(writer, request, nil)

	if err != nil {
		errnie.Error(err)
		return
	}
	current := &peer{connection: connection, endpoint: strings.TrimPrefix(request.URL.Path, "/"), channels: make(map[string]map[string]bool)}
	server.mutex.Lock()
	server.peers = append(server.peers, current)
	server.notify()
	server.mutex.Unlock()

	for {
		var message struct {
			Method string `json:"method"`
			Params struct {
				Channel string   `json:"channel"`
				Symbol  []string `json:"symbol"`
			} `json:"params"`
			Event    string   `json:"event"`
			Feed     string   `json:"feed"`
			Products []string `json:"product_ids"`
		}

		if err := connection.ReadJSON(&message); err != nil {
			if server.ctx.Err() == nil {
				errnie.Error(err)
			}
			return
		}

		if message.Method != "subscribe" && message.Event != "subscribe" {
			continue // Outbound keepalives are not recorded market inputs.
		}
		channel, symbols := message.Params.Channel, message.Params.Symbol

		if message.Feed != "" {
			channel, symbols = message.Feed, message.Products
		}
		server.mutex.Lock()

		if current.channels[channel] == nil {
			current.channels[channel] = make(map[string]bool)
		}

		for _, symbol := range symbols {
			current.channels[channel][symbol] = true
		}
		server.notify()
		server.mutex.Unlock()
	}
}

// notify is called with the subscription mutex held.
func (server *Server) notify() {
	close(server.changed)
	server.changed = make(chan struct{})
}

func (server *Server) Deliver(frame hindsight.RawFrame) error {
	// These are derived witnesses, already regenerated by Live's book reducer.
	if frame.Kind == "l3_touch" {
		server.Derived++
		return nil
	}
	connection, err := server.target(frame)

	if err != nil {
		return err
	}

	if server.First.IsZero() {
		server.First, server.Started = frame.ReceivedAt, time.Now()
		server.Source = frame.Identity.Run
	}
	deadline := server.Started.Add(frame.ReceivedAt.Sub(server.First))
	clock := time.NewTimer(time.Until(deadline))
	defer clock.Stop()

	select {
	case <-server.ctx.Done():
		return errnie.Error(server.ctx.Err())
	case <-clock.C:
	}

	if err := connection.WriteMessage(websocket.TextMessage, frame.Payload); err != nil {
		return errnie.Error(err)
	}
	server.MaxLateness = max(server.MaxLateness, time.Since(deadline))
	server.Last = frame.ReceivedAt
	server.Frames++
	return nil
}

func (server *Server) target(frame hindsight.RawFrame) (*websocket.Conn, error) {
	role, exists := server.endpoints[frame.Endpoint]

	if !exists {
		return nil, errnie.Error(errnie.Err(errnie.Validation, "replay: unknown endpoint "+frame.Endpoint, nil))
	}
	var payload struct {
		Data []struct {
			Symbol string `json:"symbol"`
		} `json:"data"`
	}
	symbol := ""

	if frame.Kind == "level3" {
		if err := json.Unmarshal(frame.Payload, &payload); err != nil {
			return nil, errnie.Error(err)
		}

		if len(payload.Data) > 0 {
			symbol = payload.Data[0].Symbol
		}
	}

	for {
		server.mutex.Lock()
		changed := server.changed

		for _, current := range server.peers {
			if current.endpoint == role &&
				(symbol == "" || current.channels[frame.Kind][symbol]) &&
				(frame.Kind != "instrument" || current.channels[frame.Kind] != nil) {
				server.mutex.Unlock()
				return current.connection, nil
			}
		}
		server.mutex.Unlock()

		select {
		case <-server.ctx.Done():
			return nil, errnie.Error(server.ctx.Err())
		case <-changed:
		}
	}
}

func (server *Server) Close() error {
	server.server.Close()
	server.mutex.Lock()
	defer server.mutex.Unlock()

	var err error
	for _, current := range server.peers {
		if closeErr := current.connection.Close(); closeErr != nil && !errors.Is(closeErr, net.ErrClosed) {
			err = errors.Join(err, errnie.Error(closeErr))
		}
	}
	return err
}
