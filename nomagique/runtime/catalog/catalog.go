/*
Package catalog is the machine-readable description of nomagique's primitives.

A nomagique pipeline is a composition of primitives, and the dashboard lets one
be drawn rather than written. Drawing it requires knowing what exists: which
primitives there are, what each one is for, and which of its arguments are
streams to be wired from other primitives rather than settings to be typed in.

That description is derived from the source rather than maintained beside it.
A hand-kept manifest of a hundred and eighty constructors is a second copy of
the truth, and the copy is what rots — this repository has already watched one
static-analysis report blank itself when the idiom it scanned for was renamed.
So the catalog is generated by reading the declarations themselves, committed
as a build artifact so a deployed binary needs no source tree, and a test
regenerates it against the live tree and fails when the two disagree.

The catalog describes; it does not execute. Composing and running a pipeline is
the concern of whatever consumes this.
*/
package catalog

import (
	_ "embed"
	"sync"

	"github.com/bytedance/sonic"
	"github.com/theapemachine/errnie"
)

/*
primitives is the generated catalog. It is regenerated by
`go run ./tools/nomagiquecatalog` and kept honest by this package's test.
*/
//go:embed primitives.json
var primitives []byte

/*
Port is one wired connection of a primitive: a stream it reads, or the stream
it produces.
*/
type Port struct {
	Name        string `json:"name"`
	Type        string `json:"type"`
	Description string `json:"description"`
}

/*
Setting is an argument that is typed in rather than wired: a constructor
parameter that is not itself a primitive.
*/
type Setting struct {
	Name        string `json:"name"`
	Type        string `json:"type"`
	Description string `json:"description,omitempty"`
}

/*
Schema describes one primitive as the editor needs it.

Op is the identity a drawn graph refers to — the package and constructor that
build the primitive, which is also what a compiler of such a graph would have
to call.
*/
type Schema struct {
	Kind        string `json:"kind"`
	Category    string `json:"category"`
	Op          string `json:"op"`
	Name        string `json:"name"`
	Label       string `json:"label"`
	Description string `json:"description"`
	Package     string `json:"package"`
	// Builder is the constructor function, e.g. NewBound. It is not called
	// "constructor": that name is inherited from Object.prototype in
	// JavaScript, and a field carrying it makes every literal the editor
	// writes fail to type-check against this schema.
	Builder  string    `json:"builder"`
	Variadic bool      `json:"variadic"`
	Inputs   []Port    `json:"inputs"`
	Outputs  []Port    `json:"outputs"`
	Config   []Setting `json:"config,omitempty"`
}

var (
	loaded map[string]Schema
	once   sync.Once
	err    error
)

/*
Primitives returns every catalogued primitive, keyed by Op. The generated
document is decoded once; a malformed one is a build fault rather than a
condition a caller can do anything about, so it surfaces as an error rather
than an empty palette that looks like a system with no primitives in it.
*/
func Primitives() (map[string]Schema, error) {
	once.Do(func() {
		decoded := make(map[string]Schema)

		if decodeErr := sonic.Unmarshal(primitives, &decoded); decodeErr != nil {
			err = errnie.Error(errnie.Err(
				errnie.Internal,
				"catalog: decode generated primitives",
				decodeErr,
			))

			return
		}

		loaded = decoded
	})

	return loaded, err
}
