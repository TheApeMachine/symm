/*
GenerateRegistry generates the compiler primitive registrations in nomagique/compiler/registry_gen.go.
It binds each primitive to its Cap'n Proto server and typed sinks without payload type-erasure.
*/
func GenerateRegistry(schemas map[string]catalog.Schema) error {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by nomagiquecatalog. DO NOT EDIT.\n\n")
	buf.WriteString("package compiler\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\tcapnp \"capnproto.org/go/capnp/v3\"\n")
	buf.WriteString("\t\"github.com/theapemachine/symm/nomagique/types\"\n")

	// Collect unique packages
	pkgImports := make(map[string]string)
	for _, s := range schemas {
		if s.ParamCount > 0 || s.TypeParamCount > 0 {
			continue
		}
		if s.Package == "" || strings.Contains(s.Package, "compiler") || strings.Contains(s.Package, "catalog") {
			continue
		}
		alias := s.Category
		if s.Package == "github.com/theapemachine/symm/nomagique/learning/associative" {
			alias = "associative"
		}
		pkgImports[alias] = s.Package
	}

	var categories []string
	for cat := range pkgImports {
		categories = append(categories, cat)
	}
	sort.Strings(categories)

	for _, cat := range categories {
		fmt.Fprintf(&buf, "\t%s %q\n", cat, pkgImports[cat])
	}
	buf.WriteString(")\n\n")

	buf.WriteString("/*\nRegisterGeneratedPrimitives registers all scanned Cap'n Proto primitives.\n*/\n")
	buf.WriteString("func RegisterGeneratedPrimitives(r *Registry) {\n")

	var ops []string
	for op := range schemas {
		ops = append(ops, op)
	}
	sort.Strings(ops)

	for _, op := range ops {
		s := schemas[op]
		if s.ParamCount > 0 || s.TypeParamCount > 0 {
			continue
		}
		if s.Package == "" || strings.Contains(s.Package, "compiler") || strings.Contains(s.Package, "catalog") {
			continue
		}
		if s.Op == "data.Source" || s.Op == "data.Sink" || s.Op == "source" || s.Op == "sink" {
			continue
		}

		alias := s.Category
		if s.Package == "github.com/theapemachine/symm/nomagique/learning/associative" {
			alias = "associative"
		}

		outType := "Float64"
		if len(s.Outputs) > 0 && s.Outputs[0].Type != "" {
			outType = s.Outputs[0].Type
		}

		fmt.Fprintf(&buf, "\t// %s\n", s.Op)
		buf.WriteString("\tr.Register(PrimitiveDescriptor{\n")
		fmt.Fprintf(&buf, "\t\tOp: %q,\n", s.Op)

		// InputPorts
		buf.WriteString("\t\tInputPorts: map[string]PortType{\n")
		for _, in := range s.Inputs {
			inType := in.Type
			if inType == "" {
				inType = "Float64"
			}
			fmt.Fprintf(&buf, "\t\t\t%q: PortType%s,\n", in.Name, inType)
		}
		hasInPort := false
		for _, in := range s.Inputs {
			if in.Name == "in" {
				hasInPort = true
				break
			}
		}

		if !hasInPort && len(s.Inputs) > 0 {
			inType := s.Inputs[0].Type
			if inType == "" {
				inType = "Float64"
			}
			fmt.Fprintf(&buf, "\t\t\t\"in\": PortType%s,\n", inType)
		}
		buf.WriteString("\t\t},\n")

		// OutputPorts
		buf.WriteString("\t\tOutputPorts: map[string]PortType{\n")
		hasOutPort := false
		for _, out := range s.Outputs {
			oType := out.Type
			if oType == "" {
				oType = "Float64"
			}
			if out.Name == "out" {
				hasOutPort = true
			}
			fmt.Fprintf(&buf, "\t\t\t%q: PortType%s,\n", out.Name, oType)
		}
		if !hasOutPort && len(s.Outputs) > 0 {
			oType := s.Outputs[0].Type
			if oType == "" {
				oType = "Float64"
			}
			fmt.Fprintf(&buf, "\t\t\t\"out\": PortType%s,\n", oType)
		}
		if len(s.Outputs) == 0 {
			fmt.Fprintf(&buf, "\t\t\t\"out\": PortType%s,\n", outType)
		}
		buf.WriteString("\t\t},\n")

		// Construct
		fmt.Fprintf(&buf, "\t\tConstruct: func(node Node) (any, capnp.Client, error) {\n")
		fmt.Fprintf(&buf, "\t\t\tsrv := %s.%s()\n", alias, s.Builder)
		if s.CapnpWrite {
			fmt.Fprintf(&buf, "\t\t\tclient := %s.%s_ServerToClient(srv)\n", alias, s.Name)
			buf.WriteString("\t\t\treturn srv, capnp.Client(client), nil\n")
		} else {
			buf.WriteString("\t\t\treturn srv, capnp.Client{}, nil\n")
		}
		buf.WriteString("\t\t},\n")

		// CreateInputSink
		buf.WriteString("\t\tCreateInputSink: map[string]func(a *InvocationAssembler) capnp.Client{\n")
		for _, in := range s.Inputs {
			inType := in.Type
			if inType == "" {
				inType = "Float64"
			}
			capName := strings.ToUpper(in.Name[:1]) + in.Name[1:]
			genSinkEntry(&buf, in.Name, inType, in.RawType, alias, s.Name, capName, s.CapnpWrite)
		}
		if !hasInPort && len(s.Inputs) > 0 {
			inType := s.Inputs[0].Type
			if inType == "" {
				inType = "Float64"
			}
			capName := strings.ToUpper(s.Inputs[0].Name[:1]) + s.Inputs[0].Name[1:]
			genSinkEntry(&buf, "in", inType, s.Inputs[0].RawType, alias, s.Name, capName, s.CapnpWrite)
		}
		buf.WriteString("\t\t},\n")

		// CreateStaticSetter
		buf.WriteString("\t\tCreateStaticSetter: map[string]func(raw any) (func(capnp.Struct), error){\n")
		for _, in := range s.Inputs {
			inType := in.Type
			if inType == "" {
				inType = "Float64"
			}
			capName := strings.ToUpper(in.Name[:1]) + in.Name[1:]
			genStaticSetterEntry(&buf, in.Name, inType, in.RawType, alias, s.Name, capName, s.CapnpWrite)
		}
		if !hasInPort && len(s.Inputs) > 0 {
			inType := s.Inputs[0].Type
			if inType == "" {
				inType = "Float64"
			}
			capName := strings.ToUpper(s.Inputs[0].Name[:1]) + s.Inputs[0].Name[1:]
			genStaticSetterEntry(&buf, "in", inType, s.Inputs[0].RawType, alias, s.Name, capName, s.CapnpWrite)
		}
		buf.WriteString("\t\t},\n")

		// BindDownstream
		genBindDownstream(&buf, s, alias, outType)

		// Invoke
		buf.WriteString("\t\tInvoke: func(ctx context.Context, client capnp.Client, setters map[string]func(capnp.Struct), downstreams map[string][]capnp.Client) error {\n")
		if s.CapnpWrite {
			fmt.Fprintf(&buf, "\t\t\tc := %s.%s(client)\n", alias, s.Name)
			fmt.Fprintf(&buf, "\t\t\terr := c.Write(ctx, func(p %s.%s_write_Params) error {\n", alias, s.Name)
			buf.WriteString("\t\t\t\tfor _, setter := range setters {\n")
			buf.WriteString("\t\t\t\t\tsetter(capnp.Struct(p))\n")
			buf.WriteString("\t\t\t\t}\n")
			buf.WriteString("\t\t\t\treturn nil\n")
			buf.WriteString("\t\t\t})\n")
			buf.WriteString("\t\t\tif err != nil {\n\t\t\t\treturn err\n\t\t\t}\n")
			buf.WriteString("\t\t\tif err := client.WaitStreaming(); err != nil {\n\t\t\t\treturn err\n\t\t\t}\n")
			fmt.Fprintf(&buf, "\t\t\tfuture, release := c.Done(ctx, nil)\n")
			buf.WriteString("\t\t\tdefer release()\n")
			buf.WriteString("\t\t\tres, err := future.Struct()\n")
			buf.WriteString("\t\t\tif err != nil {\n\t\t\t\treturn err\n\t\t\t}\n")
			buf.WriteString("\t\t\teval, _ := types.EvaluationIDFromContext(ctx)\n")
			for i, out := range s.Outputs {
				capOut := strings.ToUpper(out.Name[:1]) + out.Name[1:]
				oType := out.Type
				if oType == "" {
					oType = "Float64"
				}
				portNames := []string{out.Name}
				if i == 0 && !hasOutPort {
					portNames = append(portNames, "out")
				}
				for _, pName := range portNames {
					fmt.Fprintf(&buf, "\t\t\tif sinks, ok := downstreams[%q]; ok && len(sinks) > 0 {\n", pName)
					switch oType {
					case "Float64":
						fmt.Fprintf(&buf, "\t\t\t\tval := %s.%s_done_Results(res).%s()\n", alias, s.Name, capOut)
						buf.WriteString("\t\t\t\tfor _, s := range sinks {\n")
						buf.WriteString("\t\t\t\t\tsink := types.Float64Sink(s)\n")
						buf.WriteString("\t\t\t\t\tif capnp.Client(sink).IsValid() {\n")
						buf.WriteString("\t\t\t\t\t\t_ = sink.Write(ctx, func(p types.Float64Sink_write_Params) error {\n")
						buf.WriteString("\t\t\t\t\t\t\tp.SetEvaluation(eval)\n")
						buf.WriteString("\t\t\t\t\t\t\tp.SetValue(val)\n")
						buf.WriteString("\t\t\t\t\t\t\treturn nil\n")
						buf.WriteString("\t\t\t\t\t\t})\n")
						buf.WriteString("\t\t\t\t\t}\n")
						buf.WriteString("\t\t\t\t}\n")
					case "Int64":
						fmt.Fprintf(&buf, "\t\t\t\tval := %s.%s_done_Results(res).%s()\n", alias, s.Name, capOut)
						buf.WriteString("\t\t\t\tfor _, s := range sinks {\n")
						buf.WriteString("\t\t\t\t\tsink := types.Int64Sink(s)\n")
						buf.WriteString("\t\t\t\t\tif capnp.Client(sink).IsValid() {\n")
						buf.WriteString("\t\t\t\t\t\t_ = sink.Write(ctx, func(p types.Int64Sink_write_Params) error {\n")
						buf.WriteString("\t\t\t\t\t\t\tp.SetEvaluation(eval)\n")
						buf.WriteString("\t\t\t\t\t\t\tp.SetValue(int64(val))\n")
						buf.WriteString("\t\t\t\t\t\t\treturn nil\n")
						buf.WriteString("\t\t\t\t\t\t})\n")
						buf.WriteString("\t\t\t\t\t}\n")
						buf.WriteString("\t\t\t\t}\n")
					case "Bool":
						fmt.Fprintf(&buf, "\t\t\t\tval := %s.%s_done_Results(res).%s()\n", alias, s.Name, capOut)
						buf.WriteString("\t\t\t\tfor _, s := range sinks {\n")
						buf.WriteString("\t\t\t\t\tsink := types.BoolSink(s)\n")
						buf.WriteString("\t\t\t\t\tif capnp.Client(sink).IsValid() {\n")
						buf.WriteString("\t\t\t\t\t\t_ = sink.Write(ctx, func(p types.BoolSink_write_Params) error {\n")
						buf.WriteString("\t\t\t\t\t\t\tp.SetEvaluation(eval)\n")
						buf.WriteString("\t\t\t\t\t\t\tp.SetValue(val)\n")
						buf.WriteString("\t\t\t\t\t\t\treturn nil\n")
						buf.WriteString("\t\t\t\t\t\t})\n")
						buf.WriteString("\t\t\t\t\t}\n")
						buf.WriteString("\t\t\t\t}\n")
					case "Text":
						fmt.Fprintf(&buf, "\t\t\t\tval, _ := %s.%s_done_Results(res).%s()\n", alias, s.Name, capOut)
						buf.WriteString("\t\t\t\tfor _, s := range sinks {\n")
						buf.WriteString("\t\t\t\t\tsink := types.TextSink(s)\n")
						buf.WriteString("\t\t\t\t\tif capnp.Client(sink).IsValid() {\n")
						buf.WriteString("\t\t\t\t\t\t_ = sink.Write(ctx, func(p types.TextSink_write_Params) error {\n")
						buf.WriteString("\t\t\t\t\t\t\tp.SetEvaluation(eval)\n")
						buf.WriteString("\t\t\t\t\t\t\treturn p.SetValue(val)\n")
						buf.WriteString("\t\t\t\t\t\t})\n")
						buf.WriteString("\t\t\t\t\t}\n")
						buf.WriteString("\t\t\t\t}\n")
					default:
						fmt.Fprintf(&buf, "\t\t\t\tval, _ := %s.%s_done_Results(res).%s()\n", alias, s.Name, capOut)
						buf.WriteString("\t\t\t\tfor _, s := range sinks {\n")
						buf.WriteString("\t\t\t\t\tsink := types.DataSink(s)\n")
						buf.WriteString("\t\t\t\t\tif capnp.Client(sink).IsValid() {\n")
						buf.WriteString("\t\t\t\t\t\t_ = sink.Write(ctx, func(p types.DataSink_write_Params) error {\n")
						buf.WriteString("\t\t\t\t\t\t\tp.SetEvaluation(eval)\n")
						buf.WriteString("\t\t\t\t\t\t\treturn p.SetValue(val)\n")
						buf.WriteString("\t\t\t\t\t\t})\n")
						buf.WriteString("\t\t\t\t\t}\n")
						buf.WriteString("\t\t\t\t}\n")
					}
					buf.WriteString("\t\t\t}\n")
				}
			}
			buf.WriteString("\t\t\treturn nil\n")
		} else {
			buf.WriteString("\t\t\treturn nil\n")
		}
		buf.WriteString("\t\t},\n")

		// Done
		buf.WriteString("\t\tDone: func(ctx context.Context, client capnp.Client, downstreams map[string][]capnp.Client) error {\n")
		for i, out := range s.Outputs {
			oType := out.Type
			if oType == "" {
				oType = "Float64"
			}
			portNames := []string{out.Name}
			if i == 0 && !hasOutPort {
				portNames = append(portNames, "out")
			}
			for _, pName := range portNames {
				fmt.Fprintf(&buf, "\t\t\tif sinks, ok := downstreams[%q]; ok {\n", pName)
				buf.WriteString("\t\t\t\tfor _, s := range sinks {\n")
				fmt.Fprintf(&buf, "\t\t\t\t\tsink := types.%sSink(s)\n", oType)
				buf.WriteString("\t\t\t\t\tif capnp.Client(sink).IsValid() {\n")
				buf.WriteString("\t\t\t\t\t\t_, release := sink.Done(ctx, nil)\n")
				buf.WriteString("\t\t\t\t\t\trelease()\n")
				buf.WriteString("\t\t\t\t\t}\n")
				buf.WriteString("\t\t\t\t}\n")
				buf.WriteString("\t\t\t}\n")
			}
		}
		buf.WriteString("\t\t\treturn nil\n")
		buf.WriteString("\t\t},\n")

		buf.WriteString("\t})\n\n")
	}

	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		_ = os.WriteFile("nomagique/compiler/registry_gen.go", buf.Bytes(), 0644)
		return errnie.Error(errnie.Err(errnie.Internal, "format registry_gen.go", err))
	}

	dest := filepath.Join("nomagique", "compiler", "registry_gen.go")
	return os.WriteFile(dest, formatted, 0644)
}

func genSinkEntry(buf *bytes.Buffer, portName, portType, rawType, alias, typeName, capName string, hasCapnpWrite bool) {
	fmt.Fprintf(buf, "\t\t\t%q: func(a *InvocationAssembler) capnp.Client {\n", portName)
	switch portType {
	case "Float64":
		fmt.Fprintf(buf, "\t\t\t\treturn capnp.Client(types.NewFloat64Sink(\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context, eval uint64, val float64) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.Record(ctx, eval, %q, func(s capnp.Struct) {\n", portName)
		if hasCapnpWrite {
			fmt.Fprintf(buf, "\t\t\t\t\t\t\t%s.%s_write_Params(s).Set%s(val)\n", alias, typeName, capName)
		}
		fmt.Fprintf(buf, "\t\t\t\t\t\t})\n")
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.RecordDone(ctx, %q)\n", portName)
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t))\n")
	case "Data":
		fmt.Fprintf(buf, "\t\t\t\treturn capnp.Client(types.NewDataSink(\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context, eval uint64, val []byte) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.Record(ctx, eval, %q, func(s capnp.Struct) {\n", portName)
		if hasCapnpWrite {
			buf.WriteString("\t\t\t\t\t\t\tif len(val) > 0 {\n")
			buf.WriteString("\t\t\t\t\t\t\t\tif msg, err := capnp.Unmarshal(val); err == nil {\n")
			buf.WriteString("\t\t\t\t\t\t\t\t\tif root, err := msg.Root(); err == nil {\n")
			buf.WriteString("\t\t\t\t\t\t\t\t\t\t_ = capnp.Struct(s).SetPtr(0, root)\n")
			buf.WriteString("\t\t\t\t\t\t\t\t\t}\n")
			buf.WriteString("\t\t\t\t\t\t\t\t}\n")
			buf.WriteString("\t\t\t\t\t\t\t}\n")
		}
		fmt.Fprintf(buf, "\t\t\t\t\t\t})\n")
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.RecordDone(ctx, %q)\n", portName)
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t))\n")
	case "Bool":
		fmt.Fprintf(buf, "\t\t\t\treturn capnp.Client(types.NewBoolSink(\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context, eval uint64, val bool) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.Record(ctx, eval, %q, func(s capnp.Struct) {\n", portName)
		if hasCapnpWrite {
			fmt.Fprintf(buf, "\t\t\t\t\t\t\t%s.%s_write_Params(s).Set%s(val)\n", alias, typeName, capName)
		}
		fmt.Fprintf(buf, "\t\t\t\t\t\t})\n")
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.RecordDone(ctx, %q)\n", portName)
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t))\n")
	case "Int64":
		fmt.Fprintf(buf, "\t\t\t\treturn capnp.Client(types.NewInt64Sink(\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context, eval uint64, val int64) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.Record(ctx, eval, %q, func(s capnp.Struct) {\n", portName)
		if hasCapnpWrite {
			if strings.HasPrefix(rawType, "UInt") {
				fmt.Fprintf(buf, "\t\t\t\t\t\t\t%s.%s_write_Params(s).Set%s(uint64(val))\n", alias, typeName, capName)
			} else {
				fmt.Fprintf(buf, "\t\t\t\t\t\t\t%s.%s_write_Params(s).Set%s(val)\n", alias, typeName, capName)
			}
		}
		fmt.Fprintf(buf, "\t\t\t\t\t\t})\n")
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.RecordDone(ctx, %q)\n", portName)
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t))\n")
	case "Text":
		fmt.Fprintf(buf, "\t\t\t\treturn capnp.Client(types.NewTextSink(\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context, eval uint64, val string) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.Record(ctx, eval, %q, func(s capnp.Struct) {\n", portName)
		if hasCapnpWrite {
			fmt.Fprintf(buf, "\t\t\t\t\t\t\t_ = %s.%s_write_Params(s).Set%s(val)\n", alias, typeName, capName)
		}
		fmt.Fprintf(buf, "\t\t\t\t\t\t})\n")
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.RecordDone(ctx, %q)\n", portName)
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t))\n")
	default:
		fmt.Fprintf(buf, "\t\t\t\treturn capnp.Client(types.NewDataSink(\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context, eval uint64, val []byte) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.Record(ctx, eval, %q, func(s capnp.Struct) {\n", portName)
		if hasCapnpWrite {
			buf.WriteString("\t\t\t\t\t\t\tif len(val) > 0 {\n")
			buf.WriteString("\t\t\t\t\t\t\t\tif msg, err := capnp.Unmarshal(val); err == nil {\n")
			buf.WriteString("\t\t\t\t\t\t\t\t\tif root, err := msg.Root(); err == nil {\n")
			buf.WriteString("\t\t\t\t\t\t\t\t\t\t_ = capnp.Struct(s).SetPtr(0, root)\n")
			buf.WriteString("\t\t\t\t\t\t\t\t\t}\n")
			buf.WriteString("\t\t\t\t\t\t\t\t}\n")
			buf.WriteString("\t\t\t\t\t\t\t}\n")
		}
		fmt.Fprintf(buf, "\t\t\t\t\t\t})\n")
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t\tfunc(ctx context.Context) error {\n")
		fmt.Fprintf(buf, "\t\t\t\t\t\treturn a.RecordDone(ctx, %q)\n", portName)
		fmt.Fprintf(buf, "\t\t\t\t\t},\n")
		fmt.Fprintf(buf, "\t\t\t\t))\n")
	}
	fmt.Fprintf(buf, "\t\t\t},\n")
}

func genStaticSetterEntry(buf *bytes.Buffer, portName, portType, rawType, alias, typeName, capName string, hasCapnpWrite bool) {
	fmt.Fprintf(buf, "\t\t\t%q: func(raw any) (func(capnp.Struct), error) {\n", portName)
	switch portType {
	case "Float64":
		buf.WriteString("\t\t\t\tvar val float64\n")
		buf.WriteString("\t\t\t\tswitch v := raw.(type) {\n")
		buf.WriteString("\t\t\t\tcase float64:\n\t\t\t\t\tval = v\n")
		buf.WriteString("\t\t\t\tcase int:\n\t\t\t\t\tval = float64(v)\n")
		buf.WriteString("\t\t\t\tcase int64:\n\t\t\t\t\tval = float64(v)\n")
		buf.WriteString("\t\t\t\tcase map[string]any:\n")
		buf.WriteString("\t\t\t\t\tif f, ok := v[\"float\"].(float64); ok {\n\t\t\t\t\t\tval = f\n\t\t\t\t\t}\n")
		buf.WriteString("\t\t\t\t\tif f, ok := v[\"number\"].(float64); ok {\n\t\t\t\t\t\tval = f\n\t\t\t\t\t}\n")
		buf.WriteString("\t\t\t\t}\n")
		buf.WriteString("\t\t\t\treturn func(s capnp.Struct) {\n")
		buf.WriteString("\t\t\t\t\t_ = val\n")
		if hasCapnpWrite {
			fmt.Fprintf(buf, "\t\t\t\t\t%s.%s_write_Params(s).Set%s(val)\n", alias, typeName, capName)
		}
		buf.WriteString("\t\t\t\t}, nil\n")
	case "Int64":
		buf.WriteString("\t\t\t\tvar val int64\n")
		buf.WriteString("\t\t\t\tswitch v := raw.(type) {\n")
		buf.WriteString("\t\t\t\tcase int64:\n\t\t\t\t\tval = v\n")
		buf.WriteString("\t\t\t\tcase int:\n\t\t\t\t\tval = int64(v)\n")
		buf.WriteString("\t\t\t\tcase float64:\n\t\t\t\t\tval = int64(v)\n")
		buf.WriteString("\t\t\t\t}\n")
		buf.WriteString("\t\t\t\treturn func(s capnp.Struct) {\n")
		buf.WriteString("\t\t\t\t\t_ = val\n")
		if hasCapnpWrite {
			if strings.HasPrefix(rawType, "UInt") {
				fmt.Fprintf(buf, "\t\t\t\t\t%s.%s_write_Params(s).Set%s(uint64(val))\n", alias, typeName, capName)
			} else {
				fmt.Fprintf(buf, "\t\t\t\t\t%s.%s_write_Params(s).Set%s(val)\n", alias, typeName, capName)
			}
		}
		buf.WriteString("\t\t\t\t}, nil\n")
	case "Bool":
		buf.WriteString("\t\t\t\tval, _ := raw.(bool)\n")
		buf.WriteString("\t\t\t\treturn func(s capnp.Struct) {\n")
		buf.WriteString("\t\t\t\t\t_ = val\n")
		if hasCapnpWrite {
			fmt.Fprintf(buf, "\t\t\t\t\t%s.%s_write_Params(s).Set%s(val)\n", alias, typeName, capName)
		}
		buf.WriteString("\t\t\t\t}, nil\n")
	case "Text":
		buf.WriteString("\t\t\t\tval, _ := raw.(string)\n")
		buf.WriteString("\t\t\t\treturn func(s capnp.Struct) {\n")
		buf.WriteString("\t\t\t\t\t_ = val\n")
		if hasCapnpWrite {
			fmt.Fprintf(buf, "\t\t\t\t\t_ = %s.%s_write_Params(s).Set%s(val)\n", alias, typeName, capName)
		}
		buf.WriteString("\t\t\t\t}, nil\n")
	default:
		buf.WriteString("\t\t\t\tvar val []byte\n")
		buf.WriteString("\t\t\t\tswitch v := raw.(type) {\n")
		buf.WriteString("\t\t\t\tcase []byte:\n\t\t\t\t\tval = v\n")
		buf.WriteString("\t\t\t\tcase string:\n\t\t\t\t\tval = []byte(v)\n")
		buf.WriteString("\t\t\t\t}\n")
		buf.WriteString("\t\t\t\treturn func(s capnp.Struct) {\n")
		buf.WriteString("\t\t\t\t\t_ = val\n")
		if hasCapnpWrite {
			buf.WriteString("\t\t\t\t\tif len(val) > 0 {\n")
			buf.WriteString("\t\t\t\t\t\tif msg, err := capnp.Unmarshal(val); err == nil {\n")
			buf.WriteString("\t\t\t\t\t\t\tif root, err := msg.Root(); err == nil {\n")
			buf.WriteString("\t\t\t\t\t\t\t\t_ = capnp.Struct(s).SetPtr(0, root)\n")
			buf.WriteString("\t\t\t\t\t\t\t}\n")
			buf.WriteString("\t\t\t\t\t\t}\n")
			buf.WriteString("\t\t\t\t\t}\n")
		}
		buf.WriteString("\t\t\t\t}, nil\n")
	}
	buf.WriteString("\t\t\t},\n")
}

