package scan

import (
	"bytes"
	"fmt"
	"os"
	"sort"

	"github.com/theapemachine/symm/nomagique/catalog"
)

func GenerateRegistry(schemas map[string]catalog.Schema) error {
	var entries []catalog.Schema
	packagesUsed := make(map[string]string)

	for _, schema := range schemas {
		if schema.ParamCount > 0 || schema.TypeParamCount > 0 {
			if schema.Op != "data.Extract" {
				continue
			}
		}
		if schema.Inputs[0].Type == "T" || schema.Inputs[0].Type == "Value" || schema.Inputs[0].Type == "Outcome" {
			continue
		}
		entries = append(entries, schema)
		packagesUsed[schema.Category] = schema.Package
	}

	sort.Slice(entries, func(i, j int) bool {
		return entries[i].Op < entries[j].Op
	})

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/nomagiquecatalog. DO NOT EDIT.\n\n")
	buf.WriteString("package compiler\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"github.com/theapemachine/symm/nomagique/types\"\n")

	var sortedAliases []string
	for a := range packagesUsed {
		sortedAliases = append(sortedAliases, a)
	}
	sort.Strings(sortedAliases)

	for _, a := range sortedAliases {
		buf.WriteString(fmt.Sprintf("\t%s %q\n", a, packagesUsed[a]))
	}
	buf.WriteString(")\n\n")

	buf.WriteString("/*\n")
	buf.WriteString("Registry maps the string types from the JSON graph to factory functions\n")
	buf.WriteString("that instantiate their `Value[any, any]` wrappers. \n")
	buf.WriteString("*/\n")
	buf.WriteString("var Registry = map[string]func() types.Value[any, any]{\n")

	for _, entry := range entries {
		fmt.Fprintf(&buf, "\t\"%s\": func() types.Value[any, any] {\n", entry.Op)

		if entry.Op == "data.Extract" {
			buf.WriteString("\t\tclosure := data.NewExtract(\"value\")\n")
			buf.WriteString("\t\treturn func(in any) any {\n")
			buf.WriteString("\t\t\treturn closure(in.(map[string]any))\n")
			buf.WriteString("\t\t}\n")
			buf.WriteString("\t},\n")
			continue
		}

		var typeParam string
		if entry.TypeParamCount > 0 && (entry.Inputs[0].Type == "T" || entry.Inputs[0].Type == "Any" || entry.Inputs[0].Type == "any") {
			typeParam = "[any]"
			entry.Inputs[0].Type = "any"
		}

		fmt.Fprintf(&buf, "\t\tclosure := %s.%s%s()\n", entry.Category, entry.Builder, typeParam)
		fmt.Fprintf(&buf, "\t\treturn func(in any) any {\n")
		fmt.Fprintf(&buf, "\t\t\treturn closure(in.(%s))\n", entry.Inputs[0].Type)
		fmt.Fprintf(&buf, "\t\t}\n")
		fmt.Fprintf(&buf, "\t},\n")
	}

	buf.WriteString("}\n\n")
	buf.WriteString("/*\n")
	buf.WriteString("Primitives returns a UI-compatible definition list of available primitive nodes.\n")
	buf.WriteString("*/\n")
	buf.WriteString("func Primitives() (any, error) {\n")
	buf.WriteString("\tres := make(map[string]map[string]any)\n")
	buf.WriteString("\tfor k := range Registry {\n")
	buf.WriteString("\t\tres[k] = map[string]any{\n")
	buf.WriteString("\t\t\t\"type\":    k,\n")
	buf.WriteString("\t\t\t\"label\":   k,\n")
	buf.WriteString("\t\t\t\"inputs\":  []any{},\n")
	buf.WriteString("\t\t\t\"outputs\": []any{},\n")
	buf.WriteString("\t\t}\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn res, nil\n")
	buf.WriteString("}\n")

	content := buf.Bytes()
	
	dest := "nomagique/compiler/registry.go"
	existing, err := os.ReadFile(dest)
	if err == nil && bytes.Equal(existing, content) {
		return nil
	}

	return os.WriteFile(dest, content, 0644)
}
