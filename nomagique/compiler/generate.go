/*
GenerateCatalogAndRegistry scans the nomagique source tree, generates
nomagique/compiler/factories_gen.go (Go Cap'n Proto capability factories), and
frontend/src/components/flume/flume-config.generated.ts (native TypeScript FlumeConfig).
*/
func GenerateCatalogAndRegistry(rootDirectory string) error {
	schemas, err := ScanTree(rootDirectory)
	if err != nil {
		return errnie.Error(errnie.Err(
			errnie.Internal,
			"compiler: failed to scan primitive tree",
			err,
		))
	}

	registryCode, err := generateRegistrySource(schemas)
	if err != nil {
		return errnie.Error(errnie.Err(
			errnie.Internal,
			"compiler: failed to generate registry source",
			err,
		))
	}

	registryFile := filepath.Join(rootDirectory, "compiler", "factories_gen.go")
	if err := os.WriteFile(registryFile, registryCode, 0644); err != nil {
		return errnie.Error(errnie.Err(
			errnie.IO,
			"compiler: failed to write factories_gen.go",
			err,
		))
	}

	flumeConfigCode := generateFlumeConfigSource(schemas)
	flumeConfigFile := filepath.Join("frontend", "src", "components", "flume", "flume-config.generated.ts")
	if err := os.WriteFile(flumeConfigFile, []byte(flumeConfigCode), 0644); err != nil {
		return errnie.Error(errnie.Err(
			errnie.IO,
			"compiler: failed to write flume-config.generated.ts",
			err,
		))
	}

	return nil
}

func packageAlias(pkgPath string, category string) string {
	if pkgPath == "github.com/theapemachine/symm/nomagique/network/websocket" {
		return "netws"
	}
	if pkgPath == "github.com/theapemachine/symm/nomagique/network/http" {
		return "nethttp"
	}
	if pkgPath == "github.com/theapemachine/symm/nomagique/network/webrtc" {
		return "netwebrtc"
	}
	if pkgPath == "github.com/theapemachine/symm/nomagique/learning/associative" {
		return "associative"
	}
	if pkgPath == "github.com/theapemachine/symm/nomagique/statistic/hawkes" {
		return "hawkes"
	}
	if pkgPath == "github.com/theapemachine/symm/nomagique/store/tables" {
		return "tables"
	}
	if category != "" {
		return category
	}
	parts := strings.Split(pkgPath, "/")
	return parts[len(parts)-1]
}

func generateRegistrySource(schemas map[string]Schema) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by nomagique/compiler. DO NOT EDIT.\n\n")
	buf.WriteString("package compiler\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n\n")
	buf.WriteString("\tcapnp \"capnproto.org/go/capnp/v3\"\n")
	buf.WriteString("\t\"capnproto.org/go/capnp/v3/schemas\"\n\n")

	pkgImports := make(map[string]string)
	for _, s := range schemas {
		if s.Package == "" || strings.Contains(s.Package, "compiler") || strings.Contains(s.Package, "catalog") {
			continue
		}
		alias := packageAlias(s.Package, s.Category)
		pkgImports[alias] = s.Package
	}

	// Always ensure runtime is imported for schema registration
	if _, ok := pkgImports["runtime"]; !ok {
		pkgImports["runtime"] = "github.com/theapemachine/symm/nomagique/runtime"
	}

	var aliases []string
	for alias := range pkgImports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)

	for _, alias := range aliases {
		fmt.Fprintf(&buf, "\t%s %q\n", alias, pkgImports[alias])
	}
	buf.WriteString(")\n\n")

	// RegisterGeneratedSchemas
	buf.WriteString("/*\nRegisterGeneratedSchemas registers all scanned Cap'n Proto package schemas.\n*/\n")
	buf.WriteString("func RegisterGeneratedSchemas(reg *schemas.Registry) {\n")
	for _, alias := range aliases {
		fmt.Fprintf(&buf, "\t%s.RegisterSchema(reg)\n", alias)
	}
	buf.WriteString("\tRegisterSchema(reg)\n")
	buf.WriteString("}\n\n")

	// RegisterGeneratedPrimitives
	buf.WriteString("/*\nRegisterGeneratedPrimitives registers all scanned Cap'n Proto primitive factories.\n*/\n")
	buf.WriteString("func RegisterGeneratedPrimitives(r *Registry) {\n")

	var ops []string
	for op := range schemas {
		ops = append(ops, op)
	}
	sort.Strings(ops)

	for _, op := range ops {
		s := schemas[op]
		if s.Package == "" || strings.Contains(s.Package, "compiler") || strings.Contains(s.Package, "catalog") {
			continue
		}
		if s.Op == "data.Source" || s.Op == "data.Sink" || s.Op == "source" || s.Op == "sink" {
			continue
		}
		if !s.CapnpWrite || (!s.HasServer && !s.HasImpl) {
			continue
		}
		nonInjectedParamCount := len(s.ConstructorParams) - len(s.InjectedDeps)
		if nonInjectedParamCount > 0 || s.TypeParamCount > 0 {
			continue
		}

		alias := packageAlias(s.Package, s.Category)

		takesCtx := false
		for _, dep := range s.InjectedDeps {
			if strings.Contains(dep, "context.Context") {
				takesCtx = true
				break
			}
		}

		constructorCall := fmt.Sprintf("%s.%s()", alias, s.Builder)
		if takesCtx {
			constructorCall = fmt.Sprintf("%s.%s(ctx)", alias, s.Builder)
		}

		fmt.Fprintf(&buf, "\tr.Register(%q, Factory{\n", s.Op)
		fmt.Fprintf(&buf, "\t\tInterfaceID: %s.%s_TypeID,\n", alias, s.Name)
		buf.WriteString("\t\tNew: func(ctx context.Context, cfg []byte) (capnp.Client, error) {\n")
		fmt.Fprintf(&buf, "\t\t\treturn capnp.Client(%s.%s_ServerToClient(%s)), nil\n", alias, s.Name, constructorCall)
		buf.WriteString("\t\t},\n")
		buf.WriteString("\t})\n")
	}

	buf.WriteString("}\n\n")

	encodedJSON, err := sonic.ConfigDefault.Marshal(schemas)
	if err == nil {
		buf.WriteString("/*\nGeneratedPrimitivesJSON contains the serialized catalog of all primitive schemas.\n*/\n")
		fmt.Fprintf(&buf, "var GeneratedPrimitivesJSON = []byte(%q)\n", string(encodedJSON))
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, errnie.Error(errnie.Err(
			errnie.Internal,
			"compiler: go/format failed on generated registry",
			err,
		))
	}

	return formatted, nil
}

func tsPortBuilder(portType string) string {
	switch strings.ToLower(portType) {
	case "float64", "float32", "float":
		return "ports.float64"
	case "int64", "int32", "uint64", "uint32", "int16", "uint16", "int8", "uint8", "int", "uint":
		return "ports.int64"
	case "bool", "boolean":
		return "ports.bool"
	case "text", "string":
		return "ports.string"
	case "data", "bytes", "[]byte":
		return "ports[\"[]byte\"]"
	case "status":
		return "ports.Status"
	case "capability", "capabilitylist":
		return "ports.Capability"
	default:
		return "ports.float64"
	}
}

